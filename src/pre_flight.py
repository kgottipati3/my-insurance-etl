import logging
import psycopg2

# Enterprise logging setup
logger = logging.getLogger(__name__)

def check_table_exists(target_table: str, db_conn) -> bool:
    """
    Validates that the destination table exists in the database.
    """
    try:
        # Safely split 'public.patient' into schema and table variables
        schema, table = target_table.split('.')
    except ValueError:
        schema = 'public'
        table = target_table

    query = """
        SELECT EXISTS (
            SELECT FROM information_schema.tables 
            WHERE table_schema = %s AND table_name = %s
        );
    """
    try:
        with db_conn.cursor() as cursor:
            cursor.execute(query, (schema, table))
            exists = cursor.fetchone()[0]
            if not exists:
                logger.error(f"Pre-Flight Failure: Target table '{target_table}' does not exist.")
            return exists
    except psycopg2.Error as e:
        logger.error(f"Database error during table existence check: {e}")
        raise


def is_file_already_loaded(source_name: str, file_name: str, db_conn) -> bool:
    """
    Idempotency check: Queries the audit table to ensure we do not 
    re-process a file that has already been successfully loaded.
    """
    query = """
        SELECT EXISTS (
            SELECT 1 FROM audit.data_load_details 
            WHERE source_name = %s 
              AND file_name = %s 
              AND job_status = 'SUCCESS'
        );
    """
    try:
        with db_conn.cursor() as cursor:
            cursor.execute(query, (source_name, file_name))
            is_loaded = cursor.fetchone()[0]
            
            if is_loaded:
                logger.warning(f"Idempotency Triggered: {file_name} for '{source_name}' was already processed.")
            return is_loaded
            
    except psycopg2.Error as e:
        logger.error(f"Database error during idempotency check: {e}")
        raise


def initialize_audit_run(source_name: str, file_name: str, db_conn) -> int:
    """
    Inserts a new row into the audit table to mark the run 
    as 'STARTED' and retrieves the generated audit_id to pass down the pipeline.
    """
    query = """
        INSERT INTO audit.data_load_details (source_name, file_name, job_status)
        VALUES (%s, %s, 'STARTED')
        RETURNING audit_id;
    """
    try:
        with db_conn.cursor() as cursor:
            cursor.execute(query, (source_name, file_name))
            # Grabs the ID generated by PostgreSQL's SERIAL sequence
            audit_id = cursor.fetchone()[0]
            
        # Commit immediately so the log exists even if the pipeline crashes seconds later
        db_conn.commit()
        
        logger.info(f"Audit Run Locked. Generated audit_id: {audit_id} for '{source_name}' ({file_name})")
        return audit_id
        
    except psycopg2.Error as e:
        db_conn.rollback()
        logger.error(f"Database error during audit initialization: {e}")
        raise